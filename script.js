/* DOM helper */

const $ = id => document.getElementById(id);


/* HTML escaping helper */

const esc = s =>
  String(s).replace(/[&<>"]/g, c => ({
    "&": "&amp;",
    "<": "&lt;",
    ">": "&gt;",
    '"': "&quot;"
  }[c]));


/* External link helper */

const ext = (url, label) =>
  url
    ? `<a href="${esc(url)}" target="_blank" rel="noopener">${label} <span aria-hidden="true">&nearr;</span></a>`
    : "";


